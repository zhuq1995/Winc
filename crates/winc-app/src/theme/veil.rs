//! 「幕」系列主题：为窗口背景图设计的两深两浅四套配色。
//!
//! 背景图透出后，文字下方的底色不再是单一的颜色。取色时按最不利的情况约束对比度：背景图的
//! 不透明度为 30%，深色主题下方是纯白的图，浅色主题下方是纯黑的图，此时正文至少 6.5:1，各语法色
//! 至少 4.5:1（WCAG AA），注释和次要文字至少 3:1。因此深色主题的语法色比一般主题更亮、彩度更低，
//! 浅色主题的更深。底色取中性的冷色或暖色，不带明显的色相，以免与图片的颜色冲突；浮层的底色与
//! 卡片不同，浮层因而保持不透明。

